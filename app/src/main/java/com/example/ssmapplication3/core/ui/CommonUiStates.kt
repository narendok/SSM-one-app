@Composable
fun EnvironmentBadge(
    modifier: Modifier = Modifier,
    environment: Environment = EnvironmentConfig.currentEnvironment
) {
    if (environment.showBadge) {
        Surface(
            modifier = modifier,
            shape = RoundedCornerShape(12.dp),
            color = when (environment) {
                Environment.SHARED -> Color(0xFF455A64)
                Environment.DEV -> Color(0xFFD32F2F)
                Environment.UAT -> Color(0xFFED6C02)
                Environment.PROD -> Color.Transparent
            }
        ) {
            Text(
                text = environment.displayName,
                color = Color.White,
                fontSize = 11.sp,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp)
            )
        }
    }
}
